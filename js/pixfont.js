// Police pixel 3×5 (majuscules, chiffres, quelques symboles) pour le décor et l'écran radio.
const G = {
  A: '010101111101101', B: '110101110101110', C: '011100100100011', D: '110101101101110', E: '111100110100111',
  F: '111100110100100', G: '011100101101011', H: '101101111101101', I: '111010010010111', J: '001001001101010',
  K: '101101110101101', L: '100100100100111', M: '101111111101101', N: '110101101101101', O: '010101101101010',
  P: '110101110100100', Q: '010101101110011', R: '110101110101101', S: '011100010001110', T: '111010010010010',
  U: '101101101101111', V: '101101101101010', W: '101101111111101', X: '101101010101101', Y: '101101010010010',
  Z: '111001010100111',
  0: '111101101101111', 1: '010110010010111', 2: '111001111100111', 3: '111001111001111', 4: '101101111001001',
  5: '111100111001111', 6: '111100111101111', 7: '111001001001001', 8: '111101111101111', 9: '111101111001111',
  '-': '000000111000000', ':': '000010000010000', '.': '000000000000010', '+': '000010111010000', '/': '001001010100100',
  '!': '010010010000010', '°': '111101111000000',
};

const clean = str => String(str).normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();

export function textWidth(str, scale = 1) { return clean(str).length * 4 * scale - scale; }

export function drawText(g, str, x, y, color, scale = 1) {
  g.fillStyle = color;
  let cx = x;
  for (const ch of clean(str)) {
    const bits = G[ch];
    if (bits) {
      for (let i = 0; i < 15; i++) if (bits[i] === '1') g.fillRect(cx + (i % 3) * scale, y + Math.floor(i / 3) * scale, scale, scale);
    }
    cx += 4 * scale;
  }
}
